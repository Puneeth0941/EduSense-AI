import enum


class UserRole(str, enum.Enum):
    TEACHER = "TEACHER"
    STUDENT = "STUDENT"
    ADMIN = "ADMIN"


class SessionStatus(str, enum.Enum):
    SCHEDULED = "SCHEDULED"
    ACTIVE = "ACTIVE"
    COMPLETED = "COMPLETED"
    CANCELLED = "CANCELLED"


class AttendanceStatus(str, enum.Enum):
    PRESENT = "PRESENT"
    ABSENT = "ABSENT"
    LATE = "LATE"
    UNVERIFIED = "UNVERIFIED"
    PARTIAL = "PARTIAL"


class AttendanceEventType(str, enum.Enum):
    PRESENT_DETECTED = "PRESENT_DETECTED"
    NOT_DETECTED = "NOT_DETECTED"
    IDENTITY_VERIFIED = "IDENTITY_VERIFIED"
    IDENTITY_NOT_VERIFIED = "IDENTITY_NOT_VERIFIED"
    RETURNED = "RETURNED"
    TEMPORARILY_NOT_DETECTED = "TEMPORARILY_NOT_DETECTED"
    MISSING_CONFIRMED = "MISSING_CONFIRMED"


